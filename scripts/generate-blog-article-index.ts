import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { BLOG_ARTICLES } from '../src/registry/blogArticles';
import type { BlogArticleMeta } from '../src/types/blog';

/**
 * Generates src/registry/blogArticleIndex.ts — the slim blog-article
 * index used by the browser entry chunk (Phase 5 bundle split).
 *
 * Metadata ONLY: id, toolId, categoryId, type, status, publishedAt,
 * updatedAt, relatedToolIds, and the EN slug/title/description/
 * readingMinutes. NO bodies, NO FAQs — those live in the full EN
 * registry (src/registry/blogArticles.ts, loaded on demand by
 * ArticlePage) and in the per-locale blog.ts chunks. Keeping bodies out
 * of this index is what keeps the 4.6 MB EN registry out of the
 * initial JS bundle.
 *
 * Runs as the second step of `npm run build` (after the slug manifest,
 * before the sitemap and `vite build`), so it never goes stale.
 *
 * Run directly: `npx tsx scripts/generate-blog-article-index.ts`
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../src/registry/blogArticleIndex.ts');

const meta: BlogArticleMeta[] = BLOG_ARTICLES.map((article) => ({
  id: article.id,
  toolId: article.toolId,
  categoryId: article.categoryId,
  type: article.type,
  status: article.status,
  publishedAt: article.publishedAt,
  ...(article.updatedAt ? { updatedAt: article.updatedAt } : {}),
  relatedToolIds: article.relatedToolIds,
  en: {
    slug: article.en.slug,
    title: article.en.title,
    description: article.en.description,
    readingMinutes: article.en.readingMinutes,
  },
}));

// Sanity checks: the index must mirror the registry exactly (same ids,
// same order, no duplicates, no bodies).
const ids = new Set(meta.map((entry) => entry.id));
if (ids.size !== meta.length) {
  throw new Error(
    `Blog article index has duplicate ids (${meta.length} entries, ${ids.size} unique)`
  );
}
if (meta.length !== BLOG_ARTICLES.length) {
  throw new Error(
    `Blog article index count mismatch: ${meta.length} vs ${BLOG_ARTICLES.length} source articles`
  );
}

const header = `/**
 * Slim blog-article index — GENERATED by scripts/generate-blog-article-index.ts.
 * Do NOT edit by hand; re-run the generator (it runs in \`npm run build\`).
 *
 * Metadata only (id, tool/category, type, status, dates, related tools,
 * EN slug/title/description/readingMinutes). NO bodies, NO FAQs — those
 * live in src/registry/blogArticles.ts (full EN registry, loaded on
 * demand by ArticlePage) and in the per-locale blog.ts chunks. Keeping
 * bodies out of this index is what keeps the 4.6 MB EN registry out of
 * the initial JS bundle (see master-fix Phase 5).
 */
`;

const out =
  header +
  `\nimport type { BlogArticleMeta } from '../types/blog';\n\nexport const BLOG_ARTICLE_META: BlogArticleMeta[] = ${JSON.stringify(
    meta,
    null,
    2
  )};\n`;

writeFileSync(OUT, out);
console.log(
  `Generated blogArticleIndex.ts (${meta.length} articles, ${BLOG_ARTICLES.length} source)`
);
