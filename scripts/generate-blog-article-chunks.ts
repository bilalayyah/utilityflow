import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { BLOG_ARTICLES } from '../src/registry/blogArticles';
import type { BlogArticleLocaleVersion } from '../src/types/blog';

/**
 * Generates src/registry/articles/<article-id>.ts — one file per article
 * (registry split, perf fix Wed 2026-11-18).
 *
 * Each file holds ONLY that article's full EN version (slug, title,
 * description, body, faqs, readingMinutes) — the same shape the full
 * registry holds for that article. ArticlePage loads exactly one file
 * via src/registry/blogArticleLoader.ts, so an article page fetches
 * ~5 KB gz of article data instead of the full 1.25 MB gz registry.
 *
 * Deterministic: fixed key order, JSON.stringify with 2-space indent,
 * no timestamps, no random values — re-running produces byte-identical
 * files. Stale files (ids no longer in the registry) are removed.
 *
 * Runs as part of `npm run build` (after generate-blog-article-index,
 * before generate-sitemap and `vite build`), so it never goes stale.
 *
 * Run directly: `./node_modules/.bin/tsx scripts/generate-blog-article-chunks.ts`
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(HERE, '../src/registry/articles');

/**
 * Write with retries: the host intermittently returns EPERM on writes
 * (the "EPERM wave" — the same wave that blocks builds). A short
 * backoff ride-out keeps the generator (and `npm run build`) working
 * instead of failing on a transient block. Only EPERM is retried.
 */
function writeFileWithRetry(filePath: string, content: string): void {
  const attempts = 90;
  for (let attempt = 1; attempt <= attempts; attempt++) {
    try {
      writeFileSync(filePath, content);
      return;
    } catch (error) {
      const code = (error as NodeJS.ErrnoException)?.code;
      if (code !== 'EPERM' || attempt === attempts) throw error;
      // Synchronous sleep — keeps the generator simple and deterministic.
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1000);
    }
  }
}

const HEADER = `/**
 * Per-article EN data — GENERATED by scripts/generate-blog-article-chunks.ts.
 * Do NOT edit by hand; re-run the generator (it runs in \`npm run build\`).
 *
 * One article's full EN version (slug, title, description, body, faqs,
 * readingMinutes), split out of src/registry/blogArticles.ts so article
 * pages load only their own chunk (~5 KB gz) instead of the full
 * 1.25 MB gz registry (see master-fix/perf-diagnosis.md).
 */
`;

/** Article ids are used as filenames — reject anything unsafe. */
const SAFE_ID = /^[a-z0-9][a-z0-9-]*$/;

function toVersion(article: (typeof BLOG_ARTICLES)[number]): BlogArticleLocaleVersion {
  // Fixed key order (not source order) so output is stable regardless
  // of how the registry object was written.
  return {
    slug: article.en.slug,
    title: article.en.title,
    description: article.en.description,
    body: article.en.body,
    faqs: article.en.faqs.map((faq) => ({ q: faq.q, a: faq.a })),
    readingMinutes: article.en.readingMinutes,
  };
}

// Sanity checks on the source before writing anything.
const ids = BLOG_ARTICLES.map((article) => article.id);
if (new Set(ids).size !== ids.length) {
  throw new Error(`Blog article registry has duplicate ids (${ids.length} articles)`);
}
for (const id of ids) {
  if (!SAFE_ID.test(id)) {
    throw new Error(`Blog article id is not a safe filename: ${JSON.stringify(id)}`);
  }
}
if (ids.length === 0) {
  throw new Error('Blog article registry is empty — refusing to generate chunks');
}

mkdirSync(OUT_DIR, { recursive: true });

// Remove stale per-article files (ids no longer in the registry).
const expectedFiles = new Set(ids.map((id) => `${id}.ts`));
for (const entry of readdirSync(OUT_DIR)) {
  if (entry.endsWith('.ts') && !expectedFiles.has(entry)) {
    rmSync(resolve(OUT_DIR, entry));
    console.log(`Removed stale per-article chunk: ${entry}`);
  }
}

let written = 0;
for (const article of BLOG_ARTICLES) {
  const version = toVersion(article);
  if (!version.slug || !version.title || !version.body) {
    throw new Error(`Article ${article.id} is missing slug/title/body — refusing to generate`);
  }
  const out =
    HEADER +
    `\nimport type { BlogArticleLocaleVersion } from '../../types/blog';\n\n` +
    `export const articleEn: BlogArticleLocaleVersion = ${JSON.stringify(version, null, 2)};\n\n` +
    `export default articleEn;\n`;
  const filePath = resolve(OUT_DIR, `${article.id}.ts`);
  writeFileWithRetry(filePath, out);
  written++;
}

// Sanity checks on the output: every id present, no file empty.
const onDisk = readdirSync(OUT_DIR).filter((entry) => entry.endsWith('.ts'));
if (onDisk.length !== BLOG_ARTICLES.length) {
  throw new Error(
    `Per-article chunk count mismatch: ${onDisk.length} files on disk vs ${BLOG_ARTICLES.length} source articles`
  );
}
for (const id of ids) {
  const content = readFileSync(resolve(OUT_DIR, `${id}.ts`), 'utf8');
  if (content.trim().length === 0) {
    throw new Error(`Per-article chunk is empty: ${id}.ts`);
  }
  if (!content.includes('"body":') || !content.includes('"faqs":')) {
    throw new Error(`Per-article chunk is missing body/faqs: ${id}.ts`);
  }
}

console.log(`Generated ${written} per-article chunks in src/registry/articles/`);
