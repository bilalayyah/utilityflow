/** Write only when the content changed (keeps re-runs fast and git clean). */
function writeFileIfChanged(filePath: string, content: string): boolean {
  let existing: string | null = null;
  try {
    existing = readFileSync(filePath, 'utf8');
  } catch {
    existing = null;
  }
  if (existing === content) return false;
  writeFileWithRetry(filePath, content);
  return true;
}

const ARTICLE_LOADER_HEADER = `/**
 * Per-locale article loader — GENERATED by scripts/generate-blog-article-chunks.ts.
 * Do NOT edit by hand; re-run the generator (it runs in \`npm run build\`).
 *
 * One lazy import per generated per-article file
 * (src/locales/<code>/articles/*.ts), so Vite emits one small chunk per
 * article and an article page downloads only its own chunk — never the
 * full locale chunk (audit #6). Mirrors src/registry/blogArticleLoader.ts.
 */
`;

function articleLoaderContent(code: string): string {
  return (
    ARTICLE_LOADER_HEADER +
    `\nimport type { ArticleLocaleOverride } from '../types';\n\n` +
    `const articleModules = import.meta.glob<{ article: ArticleLocaleOverride; default: ArticleLocaleOverride }>('./articles/*.ts');\n\n` +
    `/** Article id -> lazy loader, keyed by the filename (<locale>-<id>.ts). */\n` +
    `const loadersById = new Map<string, () => Promise<{ article: ArticleLocaleOverride; default: ArticleLocaleOverride }>>();\n` +
    `for (const [path, loader] of Object.entries(articleModules)) {\n` +
    `  const match = /\\/${code}-([^/]+)\\.ts$/.exec(path);\n` +
    `  if (!match) continue;\n` +
    `  loadersById.set(match[1], loader as () => Promise<{ article: ArticleLocaleOverride; default: ArticleLocaleOverride }>);\n` +
    `}\n\n` +
    `const articleCache = new Map<string, ArticleLocaleOverride>();\n\n` +
    `/** Synchronous read of an already-loaded version (null if not loaded yet). */\n` +
    `export function getCachedArticleById(id: string): ArticleLocaleOverride | null {\n` +
    `  return articleCache.get(id) ?? null;\n` +
    `}\n\n` +
    `export async function loadArticleById(id: string): Promise<ArticleLocaleOverride | null> {\n` +
    `  const cached = articleCache.get(id);\n` +
    `  if (cached) return cached;\n` +
    `  const loader = loadersById.get(id);\n` +
    `  if (!loader) return null;\n` +
    `  try {\n` +
    `    const mod = await loader();\n` +
    `    const version = mod.article ?? mod.default;\n` +
    `    if (!version || typeof version.body !== 'string') return null;\n` +
    `    articleCache.set(id, version);\n` +
    `    return version;\n` +
    `  } catch {\n` +
    `    return null;\n` +
    `  }\n` +
    `}\n`
  );
}

const ARTICLE_FILE_HEADER = `/**
 * Per-article localized data — GENERATED by scripts/generate-blog-article-chunks.ts.
 * Do NOT edit by hand; re-run the generator (it runs in \`npm run build\`).
 *
 * One article's full localized version (slug, title, description, body,
 * faqs, readingMinutes), split out of src/locales/<code>/blog.ts so an
 * article page loads only its own chunk (~5 KB gz) instead of the full
 * locale chunk (audit #6).
 */
`;

let localizedWritten = 0;
let localizedSkipped = 0;
for (const { code, overrides, exportName } of LOCALE_OVERRIDES) {
  const localeDir = resolve(HERE, `../src/locales/${code}`);
  const articlesDir = resolve(localeDir, 'articles');
  mkdirSync(articlesDir, { recursive: true });

  const ids = Object.keys(overrides);
  if (ids.length === 0) {
    throw new Error(`Locale ${code} has no article overrides — refusing to generate`);
  }
  for (const id of ids) {
    if (!SAFE_ID.test(id)) {
      throw new Error(`Blog article id is not a safe filename: ${JSON.stringify(id)}`);
    }
  }

  // Remove stale per-article files (ids no longer in this locale).
  // Filenames are <locale>-<id>.ts so Vite's chunk names stay distinct
  // from the EN per-article chunks (<id>.ts) — the prerender's
  // articleChunkFile lookup requires exactly one <id>-<hash>.js match.
  const expectedFiles = new Set(ids.map((id) => `${code}-${id}.ts`));
  for (const entry of readdirSync(articlesDir)) {
    if (entry.endsWith('.ts') && !expectedFiles.has(entry)) {
      rmSync(resolve(articlesDir, entry));
      console.log(`Removed stale localized per-article chunk: ${code}/${entry}`);
    }
  }

  // Per-article files (full override) + the slim index record.
  const slim: Record<string, ArticleLocaleSlimOverride> = {};
  for (const id of ids) {
    const o = overrides[id];
    if (!o.slug || !o.title || !o.body) {
      throw new Error(`Locale ${code} article ${id} is missing slug/title/body — refusing to generate`);
    }
    const version: ArticleLocaleOverride = {
      slug: o.slug,
      title: o.title,
      description: o.description,
      body: o.body,
      ...(o.faqs ? { faqs: o.faqs.map((faq) => ({ q: faq.q, a: faq.a })) } : {}),
      readingMinutes: o.readingMinutes,
    };
    const out =
      ARTICLE_FILE_HEADER +
      `\nimport type { ArticleLocaleOverride } from '../../types';\n\n` +
      `export const article: ArticleLocaleOverride = ${JSON.stringify(version, null, 2)};\n\n` +
      `export default article;\n`;
    if (writeFileIfChanged(resolve(articlesDir, `${code}-${id}.ts`), out)) localizedWritten++;
    else localizedSkipped++;
    slim[id] = {
      slug: o.slug,
      title: o.title,
      description: o.description,
      readingMinutes: o.readingMinutes,
    };
  }

  const indexOut =
    `/**\n` +
    ` * Slim article index for ${code.toUpperCase()} — GENERATED by scripts/generate-blog-article-chunks.ts.\n` +
    ` * Do NOT edit by hand; re-run the generator (it runs in \`npm run build\`).\n` +
    ` *\n` +
    ` * Slug/title/description/readingMinutes only (audit #6) — this is what\n` +
    ` * the locale chunk imports. The full body + FAQs live in the per-article\n` +
    ` * files (src/locales/${code}/articles/<id>.ts) and load on demand.\n` +
    ` */\n` +
    `\nimport type { ArticleLocaleSlimOverride } from '../types';\n\n` +
    `export const ${exportName}: Record<string, ArticleLocaleSlimOverride> = ${JSON.stringify(slim, null, 2)};\n`;
  if (writeFileIfChanged(resolve(localeDir, 'blog-index.ts'), indexOut)) localizedWritten++;
  else localizedSkipped++;

  if (writeFileIfChanged(resolve(localeDir, 'articleLoader.ts'), articleLoaderContent(code))) localizedWritten++;
  else localizedSkipped++;

  // Sanity: every id present on disk, no file empty.
  const onDisk = readdirSync(articlesDir).filter((entry) => entry.endsWith('.ts'));
  if (onDisk.length !== ids.length) {
    throw new Error(
      `Localized per-article chunk count mismatch for ${code}: ${onDisk.length} files on disk vs ${ids.length} source articles`
    );
  }
  console.log(`Locale ${code}: ${ids.length} per-article chunks + blog-index + articleLoader`);
}

console.log(
  `Generated localized per-article chunks: ${localizedWritten} written, ${localizedSkipped} unchanged.`
);
